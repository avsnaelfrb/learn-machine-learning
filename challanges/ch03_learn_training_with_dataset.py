from sklearn.linear_model import LinearRegression
from sklearn.model_selection import train_test_split

def preprocessing(n_rows: int | None = None):

    df = pd.read_csv('datasets/student_exam_performance_dataset.csv')
    
    # print(df.shape)
    # print("First 5 rows:")
    # print(df.head())
